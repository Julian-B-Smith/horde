// The preview's window as GUI 3's page (B628): the embedded page in a choc WKWebView, speaking the seam signed in
// docs/proposals/gui-on-engine.md section 3 through two names. The page calls hordeNativeSend(message); a 30 fps timer
// here pushes window.hordeNativeSnapshot(snapshot). Both carry JSON text: evaluateJavascript can't carry binary, so a
// typed array crosses as a plain number array and the page's transport decodes it. The bridge itself is
// bridge_core.h and the plug-in's session (preview_plugin.cpp); this file only hosts the page.
//
// Copied from the legacy shell's host (src/gui/hypersaw_gui.mm), and for the same reasons:
// - The binding is bound in choc's ready callback, before setHTML, because choc's bindings are document-start user
//   scripts: bound after the page loads, they would never reach it.
// - The view shows one page and only that page talks to the plug-in (B446): a navigation delegate admits exactly one
//   load, the embedded page (loadHTMLString reports it as about:blank), and cancels every later one in every frame; the
//   message handler is re-registered behind a check that the message comes from that page's main frame. Page script
//   gets no clipboard, and the view takes no drops. embed_file.py gave the page a policy allowing only its own inline
//   scripts and no loads from anywhere.
// - WebKit throttles a host's child view as "background" (B79): occlusion detection and visibility-based suppression
//   go off through KVC, each in @try, so a WebKit rename degrades to a slower page, never a crash.
// Runtime class names carry a unique suffix (choc's createDelegateClass): the VST3 and AU copies of this code can share
// one process, and a fixed Objective-C class name would collide.
#import <AppKit/AppKit.h>
#import <WebKit/WebKit.h>
#include <objc/runtime.h>

#include <choc/gui/choc_WebView.h>

#include <atomic>
#include <cstring>
#include <memory>
#include <string>

#include "preview_gui.h"
#include "preview_page.h"   // generated by tools/embed_file.py: kPreviewPage_data, kPreviewPage_size

namespace {

// ADR-259's window: in plug-in mode GUI 3's page puts the device at the view's top-left at exactly this size (the GUI
// session, B628), so the window is fixed to it.
constexpr std::uint32_t kWidth = 980, kHeight = 720;
constexpr double kFrameSeconds = 1.0 / 30;   // section 3: a frame every 1/30 s

char kInnerHandlerKey;   // associated-object keys: only the address matters (non-const, so they can't be folded)
char kPageAdmittedKey;

Class nav_guard_class() {
  static Class cls = [] {
    Class c = choc::objc::createDelegateClass("NSObject", "HordePreviewNavGuard_");
    class_addMethod(c, @selector(webView:decidePolicyForNavigationAction:decisionHandler:),
                    imp_implementationWithBlock(^(id self, WKWebView*, WKNavigationAction* action, void (^decide)(WKNavigationActionPolicy)) {
                      const bool admit = !objc_getAssociatedObject(self, &kPageAdmittedKey) && action.targetFrame && action.targetFrame.isMainFrame &&
                                         [action.request.URL.absoluteString isEqualToString:@"about:blank"];
                      if (admit) objc_setAssociatedObject(self, &kPageAdmittedKey, @YES, OBJC_ASSOCIATION_RETAIN);
                      decide(admit ? WKNavigationActionPolicyAllow : WKNavigationActionPolicyCancel);
                    }),
                    "v@:@@@?");
    class_addMethod(c, @selector(userContentController:didReceiveScriptMessage:),
                    imp_implementationWithBlock(^(id self, WKUserContentController* ucc, WKScriptMessage* msg) {
                      if (!msg.frameInfo.isMainFrame || !objc_getAssociatedObject(self, &kPageAdmittedKey)) return;   // dropped unanswered
                      [objc_getAssociatedObject(self, &kInnerHandlerKey) userContentController:ucc didReceiveScriptMessage:msg];
                    }),
                    "v@:@@");
    objc_registerClassPair(c);
    return c;
  }();
  return cls;
}

void lock_to_embedded_page(choc::ui::WebView& w) {
  WKWebView* wk = (__bridge WKWebView*)w.getViewHandle();
  if (!wk) return;
  WKWebViewConfiguration* config = wk.configuration;   // a copy, sharing the live controller and preferences
  id choc_handler = (id)wk.navigationDelegate;
  id guard = [[nav_guard_class() alloc] init];
  objc_setAssociatedObject(guard, &kInnerHandlerKey, choc_handler, OBJC_ASSOCIATION_RETAIN);
  [config.userContentController removeScriptMessageHandlerForName:@"external"];
  [config.userContentController addScriptMessageHandler:guard name:@"external"];   // retains the guard
  wk.navigationDelegate = guard;                                                 // weak
  [guard release];
  @try {
    [config.preferences setValue:@NO forKey:@"javaScriptCanAccessClipboard"];
    [config.preferences setValue:@NO forKey:@"DOMPasteAllowed"];
  } @catch (NSException*) {}
  [wk unregisterDraggedTypes];
}

void configure_surface(NSView* child) {
  if (!child || ![child isKindOfClass:NSClassFromString(@"WKWebView")]) return;
  id wk = child;
  @try { [wk setValue:@NO forKey:@"windowOcclusionDetectionEnabled"]; } @catch (NSException*) {}
  @try {
    [[[wk valueForKey:@"configuration"] valueForKey:@"preferences"] setValue:@NO forKey:@"pageVisibilityBasedProcessSuppressionEnabled"];
  } @catch (NSException*) {}
  @try {
    // Always the real scale, 1 included: WebKit can read 1 in a host's child view on a retina screen, and the override
    // states the truth either way, so no test of the value is needed.
    const CGFloat scale = child.window ? child.window.backingScaleFactor : NSScreen.mainScreen.backingScaleFactor;
    [wk setValue:@(scale) forKey:@"overrideDeviceScaleFactor"];
  } @catch (NSException*) {}
}

struct GuiState {
  void* plugin = nullptr;
  std::unique_ptr<choc::ui::WebView> web;
  // Set once a frame has reached the page's hordeNativeSnapshot. Until then every frame carries everything (params,
  // presets, Voices), because frames pushed while the page is still loading are lost, and the page asks for nothing:
  // GUI 3 sends no hello. Shared, as the completion that sets it can outlive the window.
  std::shared_ptr<std::atomic<bool>> delivered = std::make_shared<std::atomic<bool>>(false);
  NSTimer* timer = nil;
};

std::string message_text(const choc::value::ValueView& args) {
  if (!args.isArray() || args.size() == 0) return {};
  const auto first = args[0];
  // The page may send the JSON text or the object itself; choc turns an object into a value, and back is exact.
  return first.isString() ? std::string(first.getString()) : choc::json::toString(first);
}

GuiState* make(void* plugin) {
  auto* g = new GuiState;
  g->plugin = plugin;
  choc::ui::WebView::Options options;
  options.acceptsFirstMouseClick = true;   // click-through focus in hosts
  options.webviewIsReady = [g](choc::ui::WebView& w) {
    lock_to_embedded_page(w);
    w.bind("hordeNativeSend", [g](const choc::value::ValueView& args) -> choc::value::Value {
      preview::bridge_receive(g->plugin, message_text(args).c_str());
      return choc::value::createInt32(1);
    });
    w.setHTML(std::string(reinterpret_cast<const char*>(kPreviewPage_data), kPreviewPage_size));
  };
  g->web = std::make_unique<choc::ui::WebView>(options);
  configure_surface((__bridge NSView*)g->web->getViewHandle());
  // A block timer: no target class to name, and it holds only the state pointer, which destroy outlives it by.
  g->timer = [NSTimer timerWithTimeInterval:kFrameSeconds
                                    repeats:YES
                                      block:^(NSTimer*) {
                                        if (!g->delivered->load()) preview::bridge_resend(g->plugin);
                                        const char* frame = preview::bridge_frame(g->plugin);
                                        auto delivered = g->delivered;
                                        g->web->evaluateJavascript(
                                            std::string("window.hordeNativeSnapshot?(window.hordeNativeSnapshot(") + frame + "),true):false",
                                            [delivered](const std::string& error, const choc::value::ValueView& result) {
                                              if (error.empty() && result.isBool() && result.getBool()) delivered->store(true);
                                            });
                                      }];
  // Common modes, or frames would stop while a host's menu or a drag holds the run loop.
  [[NSRunLoop currentRunLoop] addTimer:g->timer forMode:NSRunLoopCommonModes];
  return g;
}

GuiState* state(const clap_plugin_t* p) { return static_cast<GuiState*>(preview::gui_slot(p->plugin_data)); }

bool gui_is_api_supported(const clap_plugin_t*, const char* api, bool is_floating) { return !is_floating && !std::strcmp(api, CLAP_WINDOW_API_COCOA); }
bool gui_get_preferred_api(const clap_plugin_t*, const char** api, bool* is_floating) {
  *api = CLAP_WINDOW_API_COCOA;
  *is_floating = false;
  return true;
}
bool gui_create(const clap_plugin_t* p, const char* api, bool is_floating) {
  if (!gui_is_api_supported(p, api, is_floating)) return false;
  void*& slot = preview::gui_slot(p->plugin_data);
  if (slot) return false;
  preview::bridge_open(p->plugin_data);   // a new page knows nothing; it starts with hello
  slot = make(p->plugin_data);
  return true;
}
void gui_destroy(const clap_plugin_t* p) {
  void*& slot = preview::gui_slot(p->plugin_data);
  auto* g = static_cast<GuiState*>(slot);
  if (!g) return;
  [g->timer invalidate];   // first: the timer would otherwise tick into freed state
  [(__bridge NSView*)g->web->getViewHandle() removeFromSuperview];
  delete g;
  slot = nullptr;
}
bool gui_set_scale(const clap_plugin_t*, double) { return false; }   // AppKit scales by itself
bool gui_get_size(const clap_plugin_t*, std::uint32_t* w, std::uint32_t* h) {
  *w = kWidth;
  *h = kHeight;
  return true;
}
bool gui_can_resize(const clap_plugin_t*) { return false; }
bool gui_get_resize_hints(const clap_plugin_t*, clap_gui_resize_hints_t*) { return false; }
bool gui_adjust_size(const clap_plugin_t*, std::uint32_t* w, std::uint32_t* h) {
  *w = kWidth;
  *h = kHeight;
  return true;
}
bool gui_set_size(const clap_plugin_t*, std::uint32_t w, std::uint32_t h) { return w == kWidth && h == kHeight; }
bool gui_set_parent(const clap_plugin_t* p, const clap_window_t* window) {
  GuiState* g = state(p);
  if (!g || !window->cocoa) return false;
  NSView* parent = static_cast<NSView*>(window->cocoa);
  NSView* view = (__bridge NSView*)g->web->getViewHandle();
  [view setFrame:NSMakeRect(0, 0, kWidth, kHeight)];
  [parent addSubview:view];
  configure_surface(view);   // now the window's scale is real
  return true;
}
bool gui_set_transient(const clap_plugin_t*, const clap_window_t*) { return false; }
void gui_suggest_title(const clap_plugin_t*, const char*) {}
bool gui_show(const clap_plugin_t*) { return true; }
bool gui_hide(const clap_plugin_t*) { return true; }

const clap_plugin_gui_t kGui = {gui_is_api_supported, gui_get_preferred_api, gui_create, gui_destroy, gui_set_scale, gui_get_size, gui_can_resize,
                                gui_get_resize_hints, gui_adjust_size, gui_set_size, gui_set_parent, gui_set_transient, gui_suggest_title, gui_show, gui_hide};

}  // namespace

const clap_plugin_gui_t* preview::gui_extension() { return &kGui; }
