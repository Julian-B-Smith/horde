int g_fail = 0;
void check(bool ok, const std::string &what)
{
  std::printf("%s %s\n", ok ? "OK  " : "FAIL", what.c_str());
  if (!ok) g_fail++;
}

/* The state header's `build` key is provenance — written, never read back
   (hypersaw_clap.cpp, the B100 header comment). A re-save therefore stamps the
   CURRENT build, so comparing it would assert "the bank was generated by this
   exact commit", which is a gate that fails on the next commit for no musical
   reason. Everything else in the blob is compared byte for byte. */
std::string dropBuild(std::string s)
{
  const size_t at = s.find("\"build\":\"");
  if (at == std::string::npos) return s;
  const size_t end = s.find('"', at + 9);
  if (end == std::string::npos) return s;
  return s.erase(at, end + 1 - at + (end + 1 < s.size() && s[end + 1] == ',' ? 1 : 0));
}

std::string readAll(const fs::path &p)
{
  std::ifstream f(p, std::ios::binary);
  std::stringstream ss;
  ss << f.rdbuf();
  return ss.str();
}

/* cornerNames out of a patch blob: four JSON strings, the shell's own escape. */
std::vector<std::string> cornerNamesOf(const std::string &json)
{
  std::vector<std::string> out;
  const size_t np = json.find("\"cornerNames\"");
  if (np == std::string::npos) return out;
  const char *c = std::strchr(json.c_str() + np + 13, '[');
  for (int k = 0; c && k < 4; k++)
  {
    const char *q = std::strchr(c + 1, '"');
    if (!q) break;
    std::string v;
    const char *e = q + 1;
    for (; *e && *e != '"'; e++)
    {
      if (*e == '\\' && e[1]) { v += e[1]; e++; }
      else v += *e;
    }
    out.push_back(v);
    const char *nx = std::strchr(e, ',');
    const char *cl = std::strchr(e, ']');
    if (!nx || (cl && cl < nx)) break;
    c = nx;
  }
  return out;
}

double jsonNumber(const std::string &json, const std::string &key, double dflt)
{
  const std::string needle = "\"" + key + "\":";
  const size_t at = json.find(needle);
  return at == std::string::npos ? dflt : std::strtod(json.c_str() + at + needle.size(), nullptr);
}

/* ---- rig --------------------------------------------------------------- */

struct Rig
{
  const clap_plugin_t *p = nullptr;
  std::vector<float> L, R;
  clap_audio_buffer_t out{};
  clap_process_t proc{};
  float *ch[2];
  double peak = 0, sumSq = 0;
  size_t nSamp = 0;
  bool dirty = false;   // NaN or Inf seen

  void boot()
  {
    auto *f = (const clap_plugin_factory_t *)hypersaw_entry_get_factory(CLAP_PLUGIN_FACTORY_ID);
    p = f->create_plugin(f, &kHost, "com.lifted-truck.hypersaw");
    p->init(p);
    p->activate(p, kSR, 32, kBlock);
    p->start_processing(p);
    L.assign(kBlock, 0);
    R.assign(kBlock, 0);
    ch[0] = L.data();
    ch[1] = R.data();
    out.data32 = ch;
    out.channel_count = 2;
    proc.frames_count = kBlock;
    proc.audio_outputs = &out;
    proc.audio_outputs_count = 1;
    proc.out_events = &kOut;
  }
  void step(EvList &e)
  {
    e.finalize();
    proc.in_events = &e.list;
    p->process(p, &proc);
    for (int i = 0; i < kBlock; i++)
      for (float v : {L[i], R[i]})
      {
        if (!std::isfinite(v)) { dirty = true; continue; }
        peak = std::max(peak, (double)std::fabs(v));
        sumSq += (double)v * v;
        nSamp++;
      }
  }
  void run(double sec) { for (int i = 0; i < Math_blocks(sec); i++) { EvList e; step(e); } }
  void params(const std::vector<std::pair<clap_id, double>> &pv)
  {
    EvList e;
    for (const auto &q : pv) e.params.push_back(mkParam(q.first, q.second));
    step(e);
  }
  void note(int key, bool on, int id)
  {
    EvList e;
    e.notes.push_back(mkNote(on ? CLAP_EVENT_NOTE_ON : CLAP_EVENT_NOTE_OFF, 0, (int16_t)key, id,
                             on ? 0.9 : 0));
    step(e);
  }
  bool load(const std::string &json)
  {
    const bool ok = hypersaw_debug_apply(p, json.c_str());
    run(0.05);   // the apply is QUEUED; process() is what drains it
    return ok;
  }
  double R0() const { double r, a, b, rn; int n; hypersaw_debug_viz(p, 0, &r, &a, &b, &n, &rn); return r; }
  double RN0() const { double r, a, b, rn; int n; hypersaw_debug_viz(p, 0, &r, &a, &b, &n, &rn); return rn; }
  void viz(double &r, double &a, double &b, double &rn, int &n) const { hypersaw_debug_viz(p, 0, &r, &a, &b, &n, &rn); }
  /* Gap uniformity U = 1 - std(gap)/mean(gap) over the sorted phase gaps:
     an even lattice reads ~1, a lock ~0 (one big gap, the rest ~0), a cloud
     in between. The discriminator RN cannot be (B131). */
  double gapU() const { double ph[64]; const int n = hypersaw_debug_phases(p, 0, ph, 64); if (n < 2) return 0;
    std::vector<double> v(ph, ph + n); for (double &x : v) x = x - std::floor(x); std::sort(v.begin(), v.end());
    double mean = 1.0 / n, var = 0; for (int i = 0; i < n; i++) { const double g = (i + 1 < n ? v[i + 1] : v[0] + 1.0) - v[i]; var += (g - mean) * (g - mean); }
    const double sd = std::sqrt(var / n); return std::max(0.0, 1.0 - sd / mean); }
  double rmsDb() const
  {
    if (!nSamp) return -999;
    const double r = std::sqrt(sumSq / (double)nSamp);
    return r > 0 ? 20 * std::log10(r) : -999;
  }
  void kill() { p->stop_processing(p); p->deactivate(p); p->destroy(p); }
};

std::string saveState(const clap_plugin_t *p)
{
  static char buf[1 << 18];
  hypersaw_debug_state(p, buf, sizeof buf);
  return buf;
}

/* Strike C4 and follow R for `sec`, returning the peak R and the time it first
   crossed `want` (or -1). The swarm is sampled once per block, which is the
   same cadence publishViz feeds the GUI at. */
struct RTrace
{
  double peakR = 0, lateMaxR = 0, lateMinR = 1, lateMeanR = 0;
  double lateMinRN = 1, lateMinU = 1;   // B131: lattice observables' floors in the late window
  double tCross = -1;
  long lateN = 0;
};
RTrace strikeAndFollow(Rig &r, double sec, double want, double lateFrom)
{
  RTrace t;
  r.note(60, true, 1);
  const int blocks = Math_blocks(sec);
  for (int i = 0; i < blocks; i++)
  {
    EvList e;
    r.step(e);
    const double now = (double)(i + 1) * kBlock / kSR;
    const double R = r.R0();
    t.peakR = std::max(t.peakR, R);
    if (now >= lateFrom)
    {
      t.lateMaxR = std::max(t.lateMaxR, R);
      t.lateMinR = std::min(t.lateMinR, R);
      t.lateMinRN = std::min(t.lateMinRN, r.RN0());
      t.lateMinU = std::min(t.lateMinU, r.gapU());
      t.lateMeanR += R;
      t.lateN++;
    }
    if (t.tCross < 0 && R >= want) t.tCross = now;
  }
  if (t.lateN) t.lateMeanR /= (double)t.lateN;
  return t;
}

/* The two gated notes' current fundamentals, as the gravity law leaves them. */
bool twoVoiceRatio(Rig &r, double &ratio)
{
  char b[1024];
  hypersaw_debug_voices(r.p, b, sizeof b);
  std::vector<double> f;
  for (char *tok = std::strtok(b, ";"); tok; tok = std::strtok(nullptr, ";"))
  {
    int slot = 0, midi = 0, gate = 0, glide = 0;
    double f0 = 0, f0cur = 0, tune = 0;
    if (std::sscanf(tok, "%d,%d,%d,%lf,%lf,%d,%lf", &slot, &midi, &gate, &f0, &f0cur, &glide,
                    &tune) == 7 && gate)
      f.push_back(f0cur);
  }
  if (f.size() != 2) return false;
  std::sort(f.begin(), f.end());
  ratio = f[1] / f[0];
  return true;
}

double centsFromJust(double ratio) { return 1200.0 * std::log2(ratio / 1.5); }

