int main(int argc, char **argv)
{
  if (argc < 2)
  {
    std::fprintf(stderr, "usage: bank_check <bank-dir>   (e.g. docs/presets/factory)\n");
    return 2;
  }
  const fs::path root = argv[1];
  const char *kCats[] = {"lead", "bass", "pad", "pluck", "keys", "fx", "morph", "demo"};

  // ---- inventory ------------------------------------------------------
  std::vector<fs::path> files;
  for (const char *c : kCats)
  {
    const fs::path dir = root / c;
    if (!fs::is_directory(dir)) continue;
    for (const auto &e : fs::directory_iterator(dir))
      if (e.path().extension() == ".json") files.push_back(e.path());
  }
  std::sort(files.begin(), files.end());
  std::printf("bank: %zu patches under %s\n", files.size(), root.string().c_str());
  check(files.size() >= 30 && files.size() <= 50,
        "bank holds 30..50 patches (" + std::to_string(files.size()) + ")");

  std::vector<std::string> cornerNames;
  if (fs::is_directory(root / "corners"))
    for (const auto &e : fs::directory_iterator(root / "corners"))
      if (e.path().extension() == ".json") cornerNames.push_back(e.path().stem().string());
  std::sort(cornerNames.begin(), cornerNames.end());
  check(!cornerNames.empty(), "corners/ ships at least one corner preset");

  // ---- per file -------------------------------------------------------
  bool fxSeen[10] = {false};
  bool calibrated = false;
  for (const auto &f : files)
  {
    const std::string tag = f.parent_path().filename().string() + "/" + f.stem().string();
    const std::string blob = readAll(f);

    Rig r;
    r.boot();
    const bool applied = r.load(blob);
    check(applied, tag + ": applies");
    if (!applied) { r.kill(); continue; }

    // B: bit-identical re-save (build stamp excepted — see dropBuild)
    const std::string again = saveState(r.p);
    const bool same = dropBuild(again) == dropBuild(blob);
    check(same, tag + ": re-save is bit-identical to the file");
    if (!same)
    {
      const std::string a = dropBuild(blob), b = dropBuild(again);
      size_t i = 0;
      while (i < a.size() && i < b.size() && a[i] == b[i]) i++;
      std::printf("     first difference at byte %zu:\n       file  ...%s\n       resave...%s\n", i,
                  a.substr(i > 40 ? i - 40 : 0, 110).c_str(),
                  b.substr(i > 40 ? i - 40 : 0, 110).c_str());
    }

    // B-calibration, once: the same comparison must FAIL on a planted change.
    if (!calibrated && same)
    {
      calibrated = true;
      Rig c;
      c.boot();
      const double mv = jsonNumber(blob, "masterVol", 1.0);
      c.load(blob);
      c.params({{100, mv > 0.6 ? 0.3 : 0.9}});
      c.run(0.02);
      check(dropBuild(saveState(c.p)) != dropBuild(blob),
            "CONTROL: a planted masterVol change makes the re-save comparison FAIL");
      c.kill();
    }

    // C: it makes sound
    r.peak = 0; r.sumSq = 0; r.nSamp = 0; r.dirty = false;
    r.note(60, true, 1);
    r.run(2.0);
    const double db = r.rmsDb();
    check(!r.dirty, tag + ": no NaN/Inf in 2 s of C4");
    char msg[160];
    std::snprintf(msg, sizeof msg, "%s: RMS %.1f dBFS > -60, peak %.3f < 1.0", tag.c_str(), db,
                  r.peak);
    check(db > -60.0 && r.peak < 1.0, msg);

    // D: cornerNames name shipped corner presets, and the corners agree
    const std::vector<std::string> names = cornerNamesOf(blob);
    check(names.size() == 4, tag + ": carries cornerNames");
    check(blob.find("\"morphLayout\":2") != std::string::npos, tag + ": carries morphLayout 2");
    check(blob.find("\"schema\":3") != std::string::npos, tag + ": carries the state header");
    for (size_t k = 0; k < names.size(); k++)
    {
      if (names[k].empty()) continue;
      const fs::path cp = root / "corners" / (names[k] + ".json");
      const bool ships = fs::exists(cp);
      check(ships, tag + ": corner " + std::string(1, (char)('A' + k)) + " names a shipped preset '" +
                       names[k] + "'");
      if (!ships) continue;
      check(hypersaw_debug_cornermatches(r.p, (int)k, readAll(cp).c_str()),
            tag + ": corner " + std::string(1, (char)('A' + k)) + " matches corners/" + names[k]);
    }

    for (int slot = 1; slot <= 4; slot++)
    {
      char key[16];
      std::snprintf(key, sizeof key, "fx%dtype", slot);
      const int t = (int)jsonNumber(blob, key, 0);
      if (t > 0 && t < 10) fxSeen[t] = true;
    }
    r.kill();
  }
  check(calibrated, "the re-save comparison was calibrated on at least one file");

  // ---- every FX module the rack ships is demonstrated -----------------
  {
    const char *kFxNames[10] = {"Off",  "Drive", "Filter", "Gain", "Comp",
                               "Comb", "Notch", "Echo",   "Room", "Delay"};
    for (int t = 1; t <= 9; t++)
      check(fxSeen[t], std::string("FX type ") + kFxNames[t] + " is demonstrated by some patch");
  }

  // ---- exemplar: cloud-to-lock sweep ----------------------------------
  {
    const fs::path f = root / "demo" / "MISC - Cloud To Lock Sweep.json";
    check(fs::exists(f), "demo/MISC - Cloud To Lock Sweep ships");
    if (fs::exists(f))
    {
      const std::string blob = readAll(f);
      Rig lock;
      lock.boot();
      lock.load(blob);
      lock.params({{6, 1.0}});
      const RTrace t1 = strikeAndFollow(lock, 2.0, 0.9, 0.0);
      char m[200];
      std::snprintf(m, sizeof m, "cloud-to-lock: K 1 -> R crossed 0.9 at %.2f s (peak %.3f)",
                    t1.tCross, t1.peakR);
      check(t1.tCross >= 0 && t1.tCross <= 2.0, m);
      lock.kill();

      Rig cloud;
      cloud.boot();
      cloud.load(blob);
      cloud.params({{6, 0.0}});
      // The swarm is struck in phase, so R starts at 1 by construction and
      // falls as the voices drift; the claim is about the settled cloud, which
      // is why the window opens at 0.5 s.
      const RTrace t0 = strikeAndFollow(cloud, 2.0, 2.0, 0.5);
      /* The SETTLED order parameter, not an instantaneous bound. An uncoupled
         swarm of n voices does not sit at R = 0: its resultant is a random walk
         about 1/sqrt(n) whose instantaneous value is Rayleigh-distributed, so a
         max-based bound would be asserting a property finite-n Kuramoto does not
         have and would go red on an unlucky sample. The mean over the settled
         window IS the order parameter; the peak is printed so the fluctuation
         stays visible rather than hidden behind the average. */
      std::snprintf(m, sizeof m,
                    "cloud-to-lock: K 0 -> settled R under 0.3 (mean %.3f, min %.3f, peak %.3f)",
                    t0.lateMeanR, t0.lateMinR, t0.lateMaxR);
      check(t0.lateMeanR < 0.3, m);
      cloud.kill();
    }
  }

  // ---- exemplar: consonance-gravity chord -----------------------------
  {
    const fs::path f = root / "demo" / "MISC - Consonance Gravity Chord.json";
    check(fs::exists(f), "demo/MISC - Consonance Gravity Chord ships");
    if (fs::exists(f))
    {
      const std::string blob = readAll(f);
      double cOn = 99, cOff = 99, ratio = 0;
      Rig on;
      on.boot();
      on.load(blob);
      on.note(60, true, 1);
      on.note(67, true, 2);
      on.run(3.0);
      if (twoVoiceRatio(on, ratio)) cOn = centsFromJust(ratio);
      on.kill();

      Rig off;
      off.boot();
      off.load(blob);
      off.params({{29, 0.0}});   // Gravity off: the control
      off.note(60, true, 1);
      off.note(67, true, 2);
      off.run(3.0);
      if (twoVoiceRatio(off, ratio)) cOff = centsFromJust(ratio);
      off.kill();

      char m[200];
      std::snprintf(m, sizeof m, "gravity: C4+G4 settle to %+.3f c from 3/2 by 3 s (|.| <= 1)", cOn);
      check(std::fabs(cOn) <= 1.0, m);
      std::snprintf(m, sizeof m,
                    "CONTROL: with Gravity 0 the same fifth stays tempered at %+.3f c", cOff);
      check(std::fabs(cOff) > 1.0, m);
    }
  }

  // ---- exemplar: splay interference -----------------------------------
  {
    const fs::path f = root / "demo" / "MISC - Splay Interference.json";
    check(fs::exists(f), "demo/MISC - Splay Interference ships");
    if (fs::exists(f))
    {
      const std::string blob = readAll(f);
      Rig sp;
      sp.boot();
      sp.load(blob);
      const RTrace t = strikeAndFollow(sp, 2.0, 2.0, 1.0);
      char m[200];
      std::snprintf(m, sizeof m,
                    "splay: K -1 -> R under 0.1 after 1 s (max %.4f, mean %.4f)", t.lateMaxR,
                    t.lateMeanR);
      check(t.lateMaxR < 0.1, m);
      // B131: the lattice asserted DIRECTLY — an even splay has RN = 1, a cloud ~1/sqrt(n)
      std::printf("     splay lattice: RN min %.3f, gap uniformity U min %.3f\n", t.lateMinRN, t.lateMinU);
      // B131: the lattice asserted DIRECTLY through gap uniformity (an even
      // lattice ~0.8 here; a cloud ~0.1; a lock 0). RN cannot do this job: a
      // lock's finite phase spread scatters e^{i n theta} (measured 0.21).
      std::snprintf(m, sizeof m, "splay: the lattice's gap uniformity stays over 0.7 through the late window (min %.3f)", t.lateMinU);
      check(t.lateMinU > 0.7, m);
      sp.kill();

      Rig pos;
      pos.boot();
      pos.load(blob);
      pos.params({{6, 1.0}});
      const RTrace tp = strikeAndFollow(pos, 2.0, 0.9, 1.0);
      std::snprintf(m, sizeof m,
                    "CONTROL: the same patch at K +1 reads R over 0.9 (max %.3f) — the meter is "
                    "not dead",
                    tp.lateMaxR);
      check(tp.lateMaxR > 0.9, m);
      pos.kill();
    }
  }

  // ---- exemplar: quantum morph ----------------------------------------
  {
    const fs::path f = root / "morph" / "MO - Quantum Morph.json";
    check(fs::exists(f), "morph/MO - Quantum Morph ships");
    if (fs::exists(f))
    {
      const std::string blob = readAll(f);
      // A=(0,0) B=(1,0) C=(0,1) D=(1,1) — MorphCore::weights
      const double xy[4][2] = {{0, 0}, {1, 0}, {0, 1}, {1, 1}};
      const char *lbl[4] = {"A cloud", "B lock", "C splay", "D two-cluster"};
      double sig[4][4] = {{0}};   // R, RA, RB, RN (B131: RN separates a cloud from a splay)
      for (int k = 0; k < 4; k++)
      {
        Rig r;
        r.boot();
        r.load(blob);
        r.params({{152, xy[k][0]}, {153, xy[k][1]}});
        r.run(0.3);
        r.note(60, true, 1);
        r.run(1.0);   // past the strike transient; the corner has settled
        /* The signature is the MEAN of each order parameter over a 2 s
           window, not one instantaneous sample: at finite n every one of these
           is a fluctuating quantity, and a single sample would make the
           pairwise-separation assertion a coin toss on an unlucky block.
           min/max are printed so the fluctuation stays visible. */
        double lo[4] = {1, 1, 1, 1}, hi[4] = {0, 0, 0, 0};
        int n = 0;
        long m = 0;
        for (int i = 0; i < Math_blocks(2.0); i++)
        {
          EvList e;
          r.step(e);
          double v[4], rn;
          r.viz(v[0], v[1], v[2], rn, n);
          v[3] = r.gapU();
          for (int c = 0; c < 4; c++)
          {
            sig[k][c] += v[c];
            lo[c] = std::min(lo[c], v[c]);
            hi[c] = std::max(hi[c], v[c]);
          }
          m++;
        }
        for (int c = 0; c < 4; c++) sig[k][c] /= (double)(m ? m : 1);
        std::printf("     corner %-14s R %.3f [%.3f..%.3f]  RA %.3f  RB %.3f  U %.3f [%.3f..%.3f]  (n %d)\n", lbl[k],
                    sig[k][0], lo[0], hi[0], sig[k][1], sig[k][2], sig[k][3], lo[3], hi[3], n);
        r.kill();
      }
      for (int a = 0; a < 4; a++)
        for (int b = a + 1; b < 4; b++)
        {
          double d = 0;
          for (int c = 0; c < 4; c++) d = std::max(d, std::fabs(sig[a][c] - sig[b][c]));
          char m[160];
          std::snprintf(m, sizeof m, "quantum-morph: %s vs %s differ by %.3f (>= 0.4)", lbl[a],
                        lbl[b], d);
          check(d >= 0.4, m);
        }
    }
  }

  hypersaw_entry_deinit();
  std::printf("bank_check: %d failure(s)\n", g_fail);
  return g_fail ? 1 : 0;
}
